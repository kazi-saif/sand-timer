import {readFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
const source=await readFile(new URL('../js/hourglass.js',import.meta.url),'utf8');
const {sandGeometry,renderSand}=await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);
const start=sandGeometry(0),middle=sandGeometry(.5),end=sandGeometry(1);
assert.equal(start.lowerVisible,false);
assert.equal(end.upperVisible,false);
assert.equal(end.lowerVisible,true);
assert.ok(start.streamEnd>middle.streamEnd && middle.streamEnd>end.streamEnd);
assert.deepEqual(sandGeometry(-1),start);
assert.deepEqual(sandGeometry(2),end);
const nodes=Object.fromEntries(['#upper-sand','#lower-sand','#sand-stream'].map(id=>[id,{style:{},attributes:{},setAttribute(k,v){this.attributes[k]=v;}}]));
const svg={dataset:{},querySelector:id=>nodes[id]};
renderSand(svg,{remainingMs:500,durationMs:1000,state:'paused'});
const paused=JSON.stringify(nodes);
renderSand(svg,{remainingMs:500,durationMs:1000,state:'paused'});
assert.equal(JSON.stringify(nodes),paused,'Paused geometry must remain stable');
assert.equal(svg.dataset.state,'paused');
renderSand(svg,{remainingMs:1000,durationMs:1000,state:'idle'});
assert.equal(nodes['#lower-sand'].style.visibility,'hidden');
assert.equal(svg.dataset.state,'idle');
console.log('Sand checks passed: start/midpoint/end, clamping, pause and reset.');
