import { readFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
// Load the browser ES module without requiring a package manager or package.json.
const source = await readFile(new URL('../js/timer.js', import.meta.url), 'utf8');
const { Timer, formatTime } = await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);
let now = 1000;
const timer = new Timer(10_000, () => now);
assert.equal(timer.start().state, 'running');
now += 2300;
assert.equal(timer.pause().remainingMs, 7700);
now += 30_000;
assert.equal(timer.tick().remainingMs, 7700, 'Paused time must not elapse');
timer.start();
now += 7000;
assert.equal(timer.tick().remainingMs, 700);
now += 50_000;
assert.equal(timer.tick().state, 'complete', 'Late callbacks must reconcile the deadline');
assert.equal(timer.tick().remainingMs, 0);
assert.equal(timer.start().state, 'complete', 'Completion cannot restart accidentally');
assert.equal(timer.reset().remainingMs, 10_000);
timer.start(); now += 500; timer.start(); now += 500;
assert.equal(timer.tick().remainingMs, 9000, 'Repeated start cannot extend a session');
assert.equal(timer.reset(300_000).state, 'idle');
assert.equal(formatTime(300_000), '05:00');
assert.equal(formatTime(1), '00:01');
assert.equal(formatTime(-1), '00:00');
timer.start(); now += 300_001;
assert.equal(timer.pause().state, 'complete', 'Pause after deadline must complete');
assert.throws(() => new Timer(0), RangeError);
console.log('Timer checks passed: deadlines, pause/resume, reset, repeated start, completion and formatting.');
